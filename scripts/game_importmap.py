#!/usr/bin/env python3
"""Import maps with content hashes for the games whose code is a tree of ES modules.

The host sends no Cache-Control, so a browser may keep one module of a game from before a deploy and load another one
from after it (a new main.js with an old config.js: a broken picture until the player reloads). The page of such a game
therefore carries a generated block

    <!-- importmap:start ... -->
    <script type="importmap"> {"imports":{"/pb/ski/config.js":"/pb/ski/config.js?v=<hash>", ...}} </script>
    <link rel="modulepreload" href="/pb/ski/main.js?v=<hash>">
    <!-- importmap:end -->

Every relative or absolute import of a listed module (also computed dynamic ones) resolves to the URL with the hash of the
file's CURRENT content, so the modules a page loads always belong together, and a changed file is a new URL that no cache
holds. File names and import statements stay as they are. The first HASH_LEN hex characters of the SHA-256 are used.

    python3 scripts/game_importmap.py            # rewrite the blocks (scripts/gamedata_manifest.py does it too)
    python3 scripts/game_importmap.py --check    # exit 1 when one is stale

scripts/check_site.py (rule importmap) runs the check. After a merge conflict inside a block just run the command without
--check: the whole block is generated (it replaces the conflict markers too).
A new game: add it to PAGES, put an empty start / end marker pair at the top of <head> (before any module code) and start
the game with import("/pb/<dir>/main.js") (no ?v=).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HASH_LEN = 10
# page -> (folders whose modules go into its map, entry module). Every module of a folder is listed, so a computed import() is covered as well.
PAGES = {
    "pb/ski.html": (("pb/ski",), "pb/ski/main.js"),
    "pb/towerdefense.html": (("pb/towerdefense",), "pb/towerdefense/main.js"),
}
SKIP_DIRS = {"data", "img"}
NODE_ONLY = re.compile(r"^harness.*\.m?js$")      # Node test tools next to the modules, never loaded by a page
START = ("<!-- importmap:start (generated by scripts/game_importmap.py: every module with the hash of its content; "
         "run it after any change or merge, never edit by hand) -->")
END = "<!-- importmap:end -->"
BLOCK = re.compile(r"<!-- importmap:start\b.*?<!-- importmap:end -->", re.S)
CONFLICT = re.compile(r"^(?:<{7}|>{7}) ", re.M)
# static import / export ... from, a bare import, and import("literal")
SPECIFIER = re.compile(r"""(?:^|[;\s}])(?:import|export)\s*(?:[\w*{}\s,$]*?\sfrom\s*)?["']([^"'\n]+)["']"""
                       r"""|\bimport\(\s*["']([^"'\n]+)["']\s*\)""")
COMMENTS = re.compile(r"/\*.*?\*/|(?<![:\"'`\\])//[^\n]*", re.S)
WORKER = re.compile(r"\bnew\s+(?:Shared)?Worker\s*\(")


def read(path: str) -> str:
    with open(os.path.join(REPO, path), encoding="utf-8") as handle:
        return handle.read()


def hash_file(path: str) -> str:
    with open(os.path.join(REPO, path), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()[:HASH_LEN]


def modules_of(folders: tuple) -> list:
    """Repo-relative paths of every browser module below the folders, sorted."""
    found = []
    for folder in folders:
        for root, dirs, files in os.walk(os.path.join(REPO, folder)):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
            found.extend(os.path.relpath(os.path.join(root, name), REPO).replace(os.sep, "/")
                         for name in files if name.endswith((".js", ".mjs")) and not NODE_ONLY.match(name))
    return sorted(found)


def specifiers(code: str) -> list:
    """The literal import specifiers of a module (its comments already removed)."""
    return [static or dynamic for static, dynamic in SPECIFIER.findall(code)]


def render(page: str) -> str:
    folders, entry = PAGES[page]
    versioned = {f"/{path}": f"/{path}?v={hash_file(path)}" for path in modules_of(folders)}
    lines = ",\n".join(f"{json.dumps(key)}:{json.dumps(value)}" for key, value in versioned.items())   # one module per line: readable diffs and merges
    preload = versioned.get(f"/{entry}", f"/{entry}")
    return (f'{START}\n<script type="importmap">\n{{"imports":{{\n{lines}\n}}}}\n</script>\n'
            f'<link rel="modulepreload" href="{preload}">\n{END}')


def module_problems(page: str) -> list:
    """What an import map cannot cover, found in the modules themselves."""
    folders, entry = PAGES[page]
    listed = set(modules_of(folders))
    problems = [] if entry in listed else [f"{page}: the entry module {entry} does not exist"]
    for path in sorted(listed):
        code = COMMENTS.sub(" ", read(path))
        if WORKER.search(code):
            problems.append(f"{path} starts a worker: import maps do not reach into workers, its modules would load without a version")
        for spec in specifiers(code):
            if not spec.startswith((".", "/")):
                continue
            target, _, query = spec.partition("?")
            full = target.lstrip("/") if target.startswith("/") else os.path.normpath(os.path.join(os.path.dirname(path), target))
            if full in listed and query:
                problems.append(f"{path} imports {spec}: no ?v= on a module of the import map (the map versions it; the query makes a second copy)")
            elif full not in listed and not query:
                where = "is not in the import map" if os.path.exists(os.path.join(REPO, full)) else "does not exist"
                problems.append(f"{path} imports {spec}, which {where}")
    return problems


def page_problems(page: str, html: str) -> list:
    """Exactly one block, first in line, and the page starts its entry through the map."""
    _, entry = PAGES[page]
    blocks = BLOCK.findall(html)
    if len(blocks) != 1 or html.count("<!-- importmap:start") != 1:
        return [f"{page}: expected exactly one importmap block (markers importmap:start / importmap:end), found {len(blocks)}"]
    problems = []
    rest = BLOCK.sub("", html)
    before = html[:html.index(blocks[0])]
    if CONFLICT.search(html):
        problems.append(f"{page} has merge conflict markers")
    if re.search(r'type="module"|modulepreload|\bimport\(|<script\b[^>]*\bsrc=', before):
        problems.append(f"{page}: the importmap block must come before every module, modulepreload, import() and external script")
    if re.search(re.escape(f"/{entry}") + r"\?", rest):
        problems.append(f"{page}: start the game with /{entry} without ?v= (the import map versions it)")
    if f'"/{entry}"' not in rest:
        problems.append(f"{page} does not import /{entry}")
    return problems


def stale_entries(page: str) -> list:
    """Human readable problems of one page; empty when its map is current."""
    try:
        html = read(page)
    except OSError as error:
        return [f"{page}: {error}"]
    problems = page_problems(page, html) + module_problems(page)
    found = BLOCK.search(html)
    wanted = render(page)
    if not found or found.group(0) == wanted:
        return problems
    differing = set(found.group(0).splitlines()) ^ set(wanted.splitlines())
    changed = sorted({path for line in differing for path in re.findall(r'^"/([^"?]+)"', line)})
    more = f" and {len(changed) - 6} more" if len(changed) > 6 else ""
    detail = ", ".join(changed[:6]) + more if changed else "format"
    return [*problems, f"{page}: the import map is stale ({detail}): run python3 scripts/game_importmap.py"]


def check_all() -> list:
    return [problem for page in PAGES for problem in stale_entries(page)]


def write_all() -> list:
    """Rewrites the stale blocks; returns the pages that changed."""
    written = []
    for page in PAGES:
        html = read(page)
        block = render(page)
        fresh, count = BLOCK.subn(lambda _match: block, html)
        if count != 1:
            raise SystemExit(f"{page}: expected one importmap block, found {count} (markers importmap:start / importmap:end)")
        if fresh != html:
            with open(os.path.join(REPO, page), "w", encoding="utf-8") as handle:
                handle.write(fresh)
            written.append(page)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report stale import maps (exit 1)")
    args = parser.parse_args()
    if not args.check:
        written = write_all()
        print("import maps updated: " + (", ".join(written) if written else "nothing (all were current)"))
    problems = check_all()
    for line in problems:
        print(line)
    print("import maps: " + (f"PROBLEMS ({len(problems)})" if problems else "current"))
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
