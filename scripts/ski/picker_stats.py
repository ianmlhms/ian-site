#!/usr/bin/env python3
"""The resort picker's facts, from the baked data (so the cards show them without loading any resort):
pistes, km of pistes (sum of the run centre lines), lifts, highest and lowest point (piste ends and lift stations).

    python3 scripts/ski/picker_stats.py          # rewrites pb/ski/picker-stats.js; run after a rebake
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(REPO, "pb", "ski", "data")
OUT = os.path.join(REPO, "pb", "ski", "picker-stats.js")
RESORTS = ("killy", "3vallees", "zermatt", "arlberg", "kronplatz", "vialattea", "obertauern", "livigno", "davos", "laax", "soelden")


def stats(rid):
    with open(os.path.join(DATA, rid, "resort.json"), encoding="utf-8") as f:
        d = json.load(f)
    pistes = d["pistes"]
    # the lifts the game draws (lift-path.js: OSM stubs, a chair / gondola / cable car < 100 m with < 3 m rise, are left out)
    lifts = [l for l in d["lifts"] if not (l.get("kind") in ("chair", "gondola", "cable") and l.get("len", 0) < 100 and not (l.get("rise") or 0) >= 3)]
    tops = [p["top"] for p in pistes] + [l["top"]["y"] for l in lifts if isinstance(l.get("top"), dict) and "y" in l["top"]]
    lows = [p["bottom"] for p in pistes] + [l["bottom"]["y"] for l in lifts if isinstance(l.get("bottom"), dict) and "y" in l["bottom"]]
    return {
        "pistes": len(pistes),
        "km": round(sum(p["len"] for p in pistes) / 1000),
        "lifts": len(lifts),
        "top": round(max(tops)),
        "low": round(min(lows)),
    }


def main():
    rows = {rid: stats(rid) for rid in RESORTS}
    body = ",\n".join(f"  {json.dumps(rid)}: {json.dumps(s, separators=(', ', ': '))}" for rid, s in rows.items())
    text = ("/* Generated by scripts/ski/picker_stats.py from pb/ski/data/<rid>/resort.json (run it after a rebake). The resort picker's facts:\n"
            " * pistes, km of pistes, lifts, highest / lowest point in m. */\n"
            f"export const PICKER_STATS = Object.freeze({{\n{body},\n}});\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
