#!/usr/bin/env node
/* Lift index for the goals / cloud save (pb/ski/modes/lift-index.js): per resort the key of every lift (modes/goals-keys.js liftKey = hash5
 * of the OSM id), in a FIXED order, like the piste index. "Lifts ridden" is stored as ONE BIT PER POSITION (6 per base64 character), so
 * the order must never change: this script is APPEND-ONLY (a lift that a rebake drops stays as a dead entry, a new one goes to the end).
 * Run it after every bake / new resort (after piste_index.mjs):
 *     node scripts/ski/lift_index.mjs            (writes the file when something is new)
 *     node scripts/ski/lift_index.mjs --check    (exit 1 when a baked lift is missing: scripts/ski/goals-check.mjs does this too)
 * Then node scripts/ski/goals_data.mjs and python3 scripts/game_importmap.py. A lift missing from the index still works in the game
 * (local only, never in the cloud record). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../pb/ski');
const file = path.join(root, 'modes', 'lift-index.js');
const { liftKey } = await import(pathToFileURL(path.join(root, 'modes', 'goals-keys.js')).href);

let index = {};
if (fs.existsSync(file)) index = (await import(`${pathToFileURL(file).href}?t=${Date.now()}`)).LIFT_INDEX;
const next = { ...index };
let added = 0;
for (const rid of fs.readdirSync(path.join(root, 'data')).sort()) {
  const f = path.join(root, 'data', rid, 'resort.json');
  if (!fs.existsSync(f)) continue;
  const have = new Set((next[rid] || '').match(/.{5}/g) || []);
  let text = next[rid] || '';
  for (const l of JSON.parse(fs.readFileSync(f, 'utf8')).lifts) {
    const k = liftKey(l);
    if (!k) continue;
    if (!have.has(k)) { have.add(k); text += k; added++; }
  }
  if (text) next[rid] = text;
}
if (process.argv.includes('--check')) { console.log(added ? `lift index is missing ${added} lifts (run scripts/ski/lift_index.mjs)` : 'lift index complete'); process.exit(added ? 1 : 0); }
if (!added && fs.existsSync(file)) { console.log('lift index up to date'); process.exit(0); }
const lines = Object.entries(next).map(([rid, text]) => `  '${rid}': '${text}',`);
fs.writeFileSync(file, `/* GENERATED by scripts/ski/lift_index.mjs, APPEND-ONLY (never reorder or delete: the save stores one bit per position).
 * Per resort the liftKey (modes/goals-keys.js: hash5 of the OSM id) of every lift, 5 characters each. */
export const LIFT_INDEX = {
${lines.join('\n')}
};
`);
console.log(`lift index: +${added} lifts, ${Object.keys(next).length} resorts`);
