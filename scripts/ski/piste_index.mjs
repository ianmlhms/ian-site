#!/usr/bin/env node
/* Piste index for the compact cloud save (pb/ski/modes/piste-index.js): per resort the hash5 of every piste id, in a FIXED order.
 * The cloud record stores one 3-bit star mask per position, so the order must never change: this script is APPEND-ONLY (a piste that
 * a rebake drops stays as a dead entry, a new one goes to the end). Run it after every bake / new resort:
 *     node scripts/ski/piste_index.mjs            (writes the file when something is new)
 *     node scripts/ski/piste_index.mjs --check    (exit 1 when a baked piste is missing: scripts/ski/cloud-size-test.mjs does this too)
 * Then python3 scripts/game_importmap.py (the module is hashed in pb/ski.html). A resort / piste missing from the index still saves
 * (packed s2 fallback in cloud.js), just bigger. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../pb/ski');
const file = path.join(root, 'modes', 'piste-index.js');
const { hash5 } = await import(pathToFileURL(path.join(root, 'modes', 'challenges.js')).href);

let index = {};
if (fs.existsSync(file)) index = (await import(`${pathToFileURL(file).href}?t=${Date.now()}`)).PISTE_INDEX;
const next = {};
for (const [rid, text] of Object.entries(index)) next[rid] = text;
let added = 0;
for (const rid of fs.readdirSync(path.join(root, 'data')).sort()) {
  const f = path.join(root, 'data', rid, 'resort.json');
  if (!fs.existsSync(f)) continue;
  const have = new Set((next[rid] || '').match(/.{5}/g) || []);
  let text = next[rid] || '';
  for (const p of JSON.parse(fs.readFileSync(f, 'utf8')).pistes) {
    const h = hash5(p.id);
    if (!have.has(h)) { have.add(h); text += h; added++; }
  }
  if (text) next[rid] = text;
}
if (process.argv.includes('--check')) { console.log(added ? `piste index is missing ${added} pistes (run scripts/ski/piste_index.mjs)` : 'piste index complete'); process.exit(added ? 1 : 0); }
if (!added && fs.existsSync(file)) { console.log('piste index up to date'); process.exit(0); }
const lines = Object.entries(next).map(([rid, text]) => `  '${rid}': '${text}',`);
fs.writeFileSync(file, `/* GENERATED by scripts/ski/piste_index.mjs, APPEND-ONLY (never reorder or delete: the cloud save stores one star mask per position).
 * Per resort the hash5 of every piste id (modes/challenges.js hash5), 5 characters each. */
export const PISTE_INDEX = {
${lines.join('\n')}
};
`);
console.log(`piste index: +${added} pistes, ${Object.keys(next).length} resorts`);
