#!/usr/bin/env python3
"""Writes scripts/ski-v1.sql from every baked resort (pb/ski/data/*/resort.json): the leaderboard rules for Ski Alpen.

    python3 scripts/ski/make_sql.py

Run it again after baking a new resort (the floors table gets the new boards). The SQL is for review: the builder never applies it.
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(REPO, "pb", "ski", "data")
OUT = os.path.join(REPO, "scripts", "ski-v1.sql")
MAX_RUN_SPEED = 40      # m/s along the piste line, the same as PLAY.maxRunSpeed in pb/ski/config.js

HEAD = """-- =============================================
-- Ski Alpen (pb/ski.html, arcade id "ski"): leaderboards are TIMES.
-- Generated by scripts/ski/make_sql.py from the baked resorts. NOT applied by the builder: the reviewer runs it.
-- Idempotent.
--
-- 1. merge_score_is_better: ski-* boards are lower-is-better (like memory / maze / reaction). Without this the keep-best trigger
--    would keep the SLOWEST time and the anti-cheat would read a faster time as a worse one.
-- 2. is_idle_game: ski-* boards skip only the 1.5x "new #1" ratio rule. Boards are per piste (140+ of them) and young: a first good
--    skier beats a few casual runs by far more than 1.5x (150 s -> 95 s), which would ban honest players. The young-account rule stays.
--    Instead ski-* times get:
-- 3. a floor per board: a time faster than the piste length / 40 m/s along the piste line is impossible (the game never posts one
--    either: pb/ski/progress.js minRunMs) and is dropped by a trigger. Unknown ski-* boards get a 20 s floor.
--
-- Keep the game lists in step with the latest versions: scores-numeric-v1.sql (merge_score_is_better) and
-- anticheat-webcam-v1.sql (is_idle_game).
-- =============================================

create or replace function public.merge_score_is_better(p_game text, p_new double precision, p_old double precision)
returns boolean language sql immutable as $$
  select case when p_game in ('memory', 'maze', 'reaction') or p_game like 'ski-%'
              then p_new < p_old else p_new > p_old end
$$;
revoke all on function public.merge_score_is_better(text, double precision, double precision) from public, anon, authenticated;
grant execute on function public.merge_score_is_better(text, double precision, double precision) to service_role;

create or replace function public.is_idle_game(p_game text)
returns boolean language sql immutable as $$
  select p_game in ('idle-empire', 'cookie-clicker', 'bus-tycoon', 'park')
      or p_game like 'webcam-%'   -- anticheat-webcam-v1.sql (Kamera-Arcade)
      or p_game like 'ski-%'      -- ski-v1.sql: per-piste time boards, guarded by ski_time_floor instead
$$;

create table if not exists public.ski_board_floors (
  board text primary key check (board like 'ski-%'),
  min_ms integer not null check (min_ms >= 0)
);
alter table public.ski_board_floors enable row level security;
revoke all on table public.ski_board_floors from anon, authenticated;

create or replace function public.ski_time_floor()
returns trigger language plpgsql security definer set search_path = public as $$
declare floor_ms integer;
begin
  if new.game_id not like 'ski-%' then return new; end if;
  select f.min_ms into floor_ms from public.ski_board_floors f where f.board = new.game_id;
  if new.score is null or new.score < coalesce(floor_ms, 20000) or new.score > 3600000 then
    if tg_op = 'UPDATE' then return old; end if;
    return null;
  end if;
  return new;
end $$;
revoke all on function public.ski_time_floor() from public, anon, authenticated;
-- runs before zz_catch_suspicious_score (triggers fire in name order)
drop trigger if exists ski_time_floor on public.scores;
create trigger ski_time_floor before insert or update on public.scores
  for each row execute function public.ski_time_floor();

-- one row per piste board: length / 40 m/s, rounded down to whole seconds
"""


def main():
    rows = []
    for rid in sorted(os.listdir(DATA)):
        path = os.path.join(DATA, rid, "resort.json")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as fh:
            resort = json.load(fh)
        for p in resort["pistes"]:
            board = ("ski-%s-%s" % (rid, p["id"]))[:48]
            rows.append("  ('%s', %d)" % (board, int(p["len"] / MAX_RUN_SPEED) * 1000))
    body = HEAD + "insert into public.ski_board_floors (board, min_ms) values\n" + ",\n".join(rows) + "\non conflict (board) do update set min_ms = excluded.min_ms;\n"
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(body)
    print("wrote", OUT, len(rows), "boards")


if __name__ == "__main__":
    main()
