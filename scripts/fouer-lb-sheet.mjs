#!/usr/bin/env node
/* Writes the proofreading sheet of every string of Schueberfouer Tycoon (key, lb, de, en) as a Markdown table.
 *   node scripts/fouer-lb-sheet.mjs [output.md]
 * Default output: $HOME/Library/CloudStorage/OneDrive-Mulheims/website-overnight/reports/fouer/lb-strings.md
 * The texts live in pb/fouer/i18n.js (the lb column is a draft for Ian to proofread); the sheet lists the few strings outside it at the end. */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { STRINGS, LANGS } from "../pb/fouer/i18n.js";

const out = process.argv[2] || path.join(os.homedir(), "Library/CloudStorage/OneDrive-Mulheims/website-overnight/reports/fouer/lb-strings.md");
const cell = text => String(text ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const keys = Object.keys(STRINGS.lb);
const groups = new Map();
for (const key of keys) {
  const group = key.includes(".") ? key.slice(0, key.indexOf(".")) : key;
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(key);
}
const lines = [
  "# Schueberfouer Tycoon: all strings for the Luxembourgish proofreading",
  "",
  `${keys.length} keys in lb, de and en (pb/fouer/i18n.js), grouped by the first part of the key. The lb column is a draft written by Claude: please correct it directly here (or tell me the changes) and I will apply them to i18n.js.`,
  "Placeholders in {braces} are filled by the game (amounts, names, counts): keep them as they are.",
  "",
  `Generated by \`node scripts/fouer-lb-sheet.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
];
for (const [group, groupKeys] of groups) {
  lines.push(`## ${group} (${groupKeys.length})`, "", "| key | lb | de | en |", "|---|---|---|---|");
  for (const key of groupKeys) lines.push(`| \`${key}\` | ${LANGS.map(lang => cell(STRINGS[lang][key])).join(" | ")} |`);
  lines.push("");
}
lines.push("## Outside i18n.js", "",
  "| where | text |", "|---|---|",
  "| arcade tile name (pixelbreak.html) | Schueberfouer Tycoon |",
  "| arcade tile description lb (pixelbreak.html DESC_I18N.park) | Féier d'Schueberfouer um Glacis: lounen Plazen, bau Fahrgeschäfter a Stänn, gang duerch deng Fouer a feier déi richteg Fouerdeeg mam Hämmelsmarsch a mam Feierwierk |",
  "| arcade tile description de | Betreibe die Schueberfouer auf dem Glacis: miete Plätze, baue Fahrgeschäfte und Stände, geh durch deine Fouer und feiere die echten Fouertage mit Hämmelsmarsch und Feuerwerk |",
  "| arcade tile description en | Run the Schueberfouer on the Glacis: rent pitches, build rides and stalls, walk through your fair and join the real fair days with the Hämmelsmarsch and fireworks |",
  "| arcade about text lb (i18n-dict.js arc.about2) | ...vun der Schueberfouer bis Tower Defense a Burger Restaurant... |",
  "| live gift toast lb (pb/idle-extras.js) | 🎁 Kaddo: +{amount} Suen |",
  "| loading screen (pb/fouer.html) | Schueberfouer |",
  "| admin tab (admin-texts.js) | Suen / Attraktiounen / Pionéier-Bonus / Wäert vum ale Park / Kaddoen ugewannt |",
  "");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n"));
console.log(`${keys.length} keys, ${groups.size} groups -> ${out}`);
