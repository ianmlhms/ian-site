  const copy = { lb: {}, de: {}, en: {} };
  for (const row of ROWS) {
    const key = row[0];
    LANGS.forEach((lang, i) => {
      copy[lang][key] = row[i + 1];
    });
  }
  TS.copy = copy;
  TS.langs = LANGS;
  if (!LANGS.includes(TS.lang)) TS.lang = 'lb';

  function t(key, vars, langOverride) {
    const lang = LANGS.includes(langOverride) ? langOverride : TS.lang;
    const raw = (copy[lang] && copy[lang][key]) ?? copy.lb[key] ?? copy.en[key];
    if (raw === undefined) return key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : m));
  }
  /* Route/train names are {lb,de,en} objects. */
  function pick(obj, langOverride) {
    if (!obj || typeof obj !== 'object') return obj === undefined ? '' : String(obj);
    return obj[langOverride || TS.lang] || obj.lb || obj.en || '';
  }
  function setLang(lang) {
    if (!LANGS.includes(lang)) {
      console.warn('[Lokféierer] unknown language', lang);
      return TS.lang;
    }
    TS.lang = lang;
    try {
      document.documentElement.lang = lang === 'lb' ? 'lb' : lang;
    } catch (_) {
      /* no DOM (tests) */
    }
    return lang;
  }
  TS.t = t;
  TS.pick = pick;
  TS.setLang = setLang;
