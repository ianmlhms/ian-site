/* Lokféierer: route definitions (authored layouts).
 *
 * A route is a list of layout items that TS.track.build() turns into a smooth 3D curve:
 *   { t:'s', len }                       straight
 *   { t:'c', len, r, dir:'L'|'R' }       curve (radius in m, left or right turn)
 *   { t:'station', name, size, side }    level straight with a platform
 * Optional per-item fields: g (grade in %), limit (km/h), biome, tunnel, crossing,
 * bridge:{kind:'viaduct'|'steel'|'river', h (height above valley), water}.
 *
 * Layouts are authored with a tiny token language, see parseLeg():
 *   s200            straight, 200 m          s*          straight, fills what is left of the leg
 *   r450/230        right curve R450, 230 m  l600/200    left curve
 *   flags (after ':'): g0.8 grade % | v90 limit | T tunnel | X level crossing | bfarmland biome
 *                      Bs,36,w bridge (v|s|r = viaduct|steel|river, height m, w = water below)
 */
(function () {
  'use strict';
  window.TS = window.TS || {};

  const BRIDGE_KINDS = { v: 'viaduct', s: 'steel', r: 'river' };

  const STATION_DEFAULTS = {
    rail: { platformLen: 210, approachBefore: 40, approachAfter: 40, stationLimit: 80 },
    hst: { platformLen: 260, approachBefore: 40, approachAfter: 40, stationLimit: 160 },
    tram: { platformLen: 40, approachBefore: 20, approachAfter: 20, stationLimit: 25 },
  };

  function parseFlags(flags) {
    const out = {};
    flags.forEach((flag) => {
      const key = flag[0];
      const val = flag.slice(1);
      if (key === 'g') out.g = parseFloat(val);
      else if (key === 'v') out.limit = parseInt(val, 10);
      else if (key === 'T') out.tunnel = true;
      else if (key === 'X') out.crossing = true;
      else if (key === 'b') out.biome = val;
      else if (key === 'B') {
        const [k, h, w] = val.split(',');
        out.bridge = { kind: BRIDGE_KINDS[k] || 'viaduct', h: parseFloat(h) || 10, water: w === 'w' };
      } else console.warn('[Lokféierer] routes: unknown flag', flag);
    });
    return out;
  }

  function parseToken(token) {
    const [head, ...flags] = token.split(':');
    const extra = parseFlags(flags);
    if (head === 's*') return Object.assign({ t: 's', len: 0, fill: true }, extra);
    if (head[0] === 's') return Object.assign({ t: 's', len: parseFloat(head.slice(1)) }, extra);
    const m = head.match(/^([rl])(\d+)\/(\d+)$/);
    if (!m) throw new Error('[Lokféierer] routes: bad token ' + token);
    return Object.assign({ t: 'c', dir: m[1] === 'r' ? 'R' : 'L', r: parseInt(m[2], 10), len: parseInt(m[3], 10) }, extra);
  }

  // Expand one leg (between two stations) to exactly `length` metres.
  function leg(length, spec) {
    const items = spec.trim().split(/\s+/).map(parseToken);
    const fixed = items.reduce((sum, it) => sum + it.len, 0);
    const fills = items.filter((it) => it.fill);
    const rest = Math.max(30, length - fixed) / Math.max(1, fills.length);
    if (length - fixed < 30) console.warn('[Lokféierer] routes: leg overfull', length, fixed);
    return items.map((it) => (it.fill ? Object.assign({}, it, { len: rest, fill: undefined }) : it));
  }

  /* pw = platform width in m (default by size: 5.2, big stations 7); real stations that are narrower say so */
  const station = (name, size, side, biome, terminus, pw) => ({ t: 'station', name, size, side, biome, terminus: !!terminus, pw });

  function makeRoute(def, body) {
    const stations = body.filter((it) => it.t === 'station').map((it) => it.name);
    const layout = body.reduce((acc, it) => acc.concat(it), []);
    const defaults = STATION_DEFAULTS[def.kind];
    const stationLen = defaults.approachBefore + defaults.platformLen + defaults.approachAfter;
    const lengthM = layout.reduce((sum, it) => sum + (it.t === 'station' ? stationLen : it.len), 0);
    const passNames = Object.freeze((def.passNames || []).filter((n, i, all) => stations.indexOf(n) > 0 && stations.indexOf(n) < stations.length - 1 && all.indexOf(n) === i));
    return Object.freeze(Object.assign({ stationDefaults: defaults, stations, layout, lengthM, stopCount: stations.length - passNames.length, sceneryId: def.id }, def, { passNames }));
  }

  /* ------------------------------------------------- the real single-line routes: west (line 50), south (line 60), north (line 10)
   * Curves, grades, bridges, tunnels, level crossings and biomes of every leg come from the real OSM railway geometry (real-<id>.js, generated by
   * scripts/zuch/build_real_route.py, W2c in REAL-LINES.md); the stop lists are the real ones (OSM route relations CFL-1 / CFL-50 / CFL-60).  Every leg item carries
   * its `legId`, which the scenery data (data/real/<id>-features.json) is keyed by. */
  const realLineBody = (id) => {
    const RL = window.TS.realLines && window.TS.realLines[id];
    if (!RL) throw new Error('[Lokféierer] routes: real-' + id + '.js is missing');
    return RL.segments.main.reduce((acc, it) => {
      if (it.t === 'station') {
        const st = RL.stations[it.name];
        /* Lëtzebuerg Gare Centrale is the same real station on every route (the patch, like the Mosel one, is bound to the LEFT
         * side of the track); each real-<id>.js was fit independently from its own OSM platform search and may disagree. */
        const side = it.name === 'Lëtzebuerg' ? 'left' : st.side;
        return acc.concat([station(it.name, st.size, side, st.biome, false, PLATFORM_WIDTH_LU[it.name])]);
      }
      return acc.concat(leg(it.length, it.spec).map((x) => Object.assign({}, x, { legId: it.id })));
    }, []);
  };
  const lastAsTerminus = (body) => body.map((it, i, all) => (i === all.length - 1 ? Object.assign({}, it, { terminus: true }) : it));
  const PLATFORM_WIDTH_LU = {};

  /* ---------------------------------------------------------------- 1 west (CFL line 50: Luxembourg - Bertrange-Strassen - Mamer-Lycée - Mamer - Capellen - Kleinbettingen, the trains go on to Arlon) */
  const west = makeRoute(
    {
      id: 'west', kind: 'rail', region: 'West', cruise: 120, biomes: ['city', 'suburb', 'farmland', 'industrial', 'forest'],
      name: { lb: 'Lëtzebuerg – Kleinbettingen', de: 'Luxemburg – Kleinbettingen', en: 'Luxembourg – Kleinbettingen' },
    },
    lastAsTerminus(realLineBody('west'))
  );

  /* --------------------------------------------------------------- 2 south (CFL line 60, all stops: Luxembourg - Bettembourg - Esch - Belval - Differdange - Pétange - Rodange) */
  const south = makeRoute(
    {
      id: 'south', kind: 'rail', region: 'Minett', cruise: 120, biomes: ['city', 'suburb', 'farmland', 'industrial', 'forest'],
      name: { lb: 'Lëtzebuerg – Esch-Uelzecht – Rodange', de: 'Luxemburg – Esch – Rodange', en: 'Luxembourg – Esch – Rodange' },
    },
    lastAsTerminus(realLineBody('south'))
  );

  /* --------------------------------------------------------------- 4 north (CFL line 10, all stops as far as Clervaux; the real line goes on to Troisvierges) */
  const north = makeRoute(
    {
      id: 'north', kind: 'rail', region: 'Norden', cruise: 100, biomes: ['city', 'suburb', 'farmland', 'forest', 'ardennes', 'industrial'],
      name: { lb: 'Lëtzebuerg – Ettelbréck – Clierf', de: 'Luxemburg – Ettelbrück – Clerf', en: 'Luxembourg – Ettelbruck – Clervaux' },
    },
    lastAsTerminus(realLineBody('north'))
  );

  /* ------------------------------------------------- the Mosel line (east, wittlich, trier)
   * Lëtzebuerg - Cents-Hamm - Sandweiler-Contern - Oetrange - Munsbach - Roodt-Syr - Betzder - Wecker - Manternach - Mertert - Wasserbëlleg - Igel, then
   *   west branch (RB 83 since 3 Mar 2025, left bank of the Mosel): Tréier-Zewen - Tréier-Euren - Tréier West - Tréier-Pallien
   *   Hbf branch (RE 11 / RE 1, right bank + Moselstrecke): Kreuz Konz - Tréier Süd - Tréier Hbf
   * both meet again before Tréier Hafestrooss - Ehrang Ort - Quint - Schweich - Föhren - Hetzerath - Sehlem - Salmtal - Wittlich - Cochem - Koblenz Hbf.
   * The curves, grades, bridges, tunnels, crossings and biomes of every leg up to Wittlich come from the real OSM railway geometry (real-mosel.js, generated by
   * scripts/zuch/build_real_line.py, method in REAL-LINES.md).  The two branches have the same length, so the shared tail has the same s on both services; every
   * leg item carries its `legId`, which the scenery data (data/real/mosel-features.json) is keyed by.  Three services:
   *   east = up to Wasserbëlleg (all stops), wittlich = A + west branch + tail up to Wittlich (all stops, the RB 83 of the real timetable),
   *   trier = A + Hbf branch + tail + Cochem + Koblenz as an express (passNames: the stations it runs through at line speed).
   * See pb/train-sim/REAL-LINES.md for the real stop list and its sources. */
  const RM = window.TS.realMosel;
  if (!RM) throw new Error('[Lokféierer] routes: real-mosel.js is missing');
  const PLATFORM_WIDTH = { Munsbach: 3.2, 'Roodt-Syr': 2.7, Oetrange: 5.7, Betzder: 2.6, Wecker: 4.1, 'Sandweiler-Contern': 3.7, Mertert: 2.7, Manternach: 3.3, 'Wasserbëlleg': 5.8, 'Cents-Hamm': 6.2, Schweich: 8.1, Wittlich: 6.5, Hetzerath: 5.6, 'Föhren': 6.0, Sehlem: 7.0, Salmtal: 7.0, 'Tréier Süd': 6.0, 'Kreuz Konz': 5.1, Igel: 3.0, 'Tréier-Zewen': 3.4, 'Tréier-Euren': 2.6, 'Tréier West': 2.8, 'Tréier-Pallien': 2.2, 'Tréier Hafestrooss': 7.0, 'Ehrang Ort': 3.4, Quint: 6.0 };
  /* the OSM-derived side of these stops contradicts the photos / the station patch (Wecker: the real platform is an island on the LEFT of the track that has the building
   * on its right; real-mosel.js says 'right'): corrected here until build_real_line.py learns it (real-mosel.js is generated and stays untouched) */
  const SIDE_FIX = { 'Lëtzebuerg': 'left', Wecker: 'left', Manternach: 'right', 'Tréier West': 'right', Schweich: 'right', Hetzerath: 'right', 'Tréier Süd': 'right' };   // the side of the real station building (platform and patch agree); real-mosel.js (generated) has the side of the first OSM platform found
  const realStation = (name) => {
    const st = RM.stations[name];
    return station(name, st.size, SIDE_FIX[name] || st.side, st.biome, false, PLATFORM_WIDTH[name]);
  };
  const realSegment = (seg) => RM.segments[seg].reduce((acc, it) => {
    if (it.t === 'station') return acc.concat([realStation(it.name)]);
    return acc.concat(leg(it.length, it.spec).map((x) => Object.assign({}, x, { legId: it.id })));
  }, []);
  const moselA = realSegment('A');
  const moselW = realSegment('W');
  const moselH = realSegment('H');
  const moselB = realSegment('B');
  /* beyond Wittlich the express still runs on the authored legs (the real line there is 28 / 48 km long) */
  const moselTail = [
    ...leg(2200, 's300:v120:bvineyard l1000/300:g-0.5 s*:v140 s560:T:v120 r900/320 s*'),
    station('Cochem', 2, 'left', 'vineyard'),
    ...leg(1800, 's300:v120:briver r1000/320 s*:v140 l1100/300:bsuburb s200:v100:bcity'),
    station('Koblenz Hbf', 3, 'right', 'city'),
  ];
  const MOSEL_PASS_LIMIT = 110;
  const moselBodyWest = [...moselA, ...moselW, ...moselB];
  const moselBodyHbf = [...moselA, ...moselH, ...moselB, ...moselTail];
  const sliceTo = (body, lastStation) => {
    const end = body.findIndex((it) => it.t === 'station' && it.name === lastStation);
    return body.slice(0, end + 1).map((it, i, all) => (i === all.length - 1 ? Object.assign({}, it, { terminus: true }) : it));
  };
  const moselSlice = (lastStation) => sliceTo(lastStation === 'Wittlich' ? moselBodyWest : lastStation === 'Wasserbëlleg' ? moselBodyWest : moselBodyHbf, lastStation);
  const MOSEL_BIOMES = ['city', 'suburb', 'farmland', 'forest', 'river', 'vineyard', 'industrial'];
  const MOSEL_STOPS_TRIER = ['Lëtzebuerg', 'Sandweiler-Contern', 'Wasserbëlleg', 'Igel', 'Kreuz Konz', 'Tréier Süd', 'Tréier Hbf', 'Schweich', 'Föhren', 'Wittlich', 'Cochem', 'Koblenz Hbf'];

  /* ---------------------------------------------------------------- 3 east (all stops, ends at Wasserbëlleg) */
  const east = makeRoute(
    {
      id: 'east', kind: 'rail', region: 'Ost', cruise: 120, biomes: MOSEL_BIOMES, sceneryId: 'mosel',
      name: { lb: 'Lëtzebuerg – Wasserbëlleg', de: 'Luxemburg – Wasserbillig', en: 'Luxembourg – Wasserbillig' },
    },
    moselSlice('Wasserbëlleg')
  );

  /* ------------------------------------------------- 3b wittlich (all stops, the RB 83) */
  const wittlich = makeRoute(
    {
      id: 'wittlich', kind: 'rail', region: 'Ost', cruise: 120, biomes: MOSEL_BIOMES, sceneryId: 'mosel',
      name: { lb: 'Lëtzebuerg – Tréier – Wittlech', de: 'Luxemburg – Trier – Wittlich', en: 'Luxembourg – Trier – Wittlich' },
    },
    moselSlice('Wittlich')
  );

  /* --------------------------------------------------------------- 6 trier (express: RE 11 + RE 1 to Koblenz) */
  const trier = makeRoute(
    {
      id: 'trier', kind: 'rail', region: 'Däitschland', cruise: 140, biomes: MOSEL_BIOMES, sceneryId: 'mosel',
      name: { lb: 'Lëtzebuerg – Tréier – Koblenz', de: 'Luxemburg – Trier – Koblenz', en: 'Luxembourg – Trier – Koblenz' },
      passNames: moselBodyHbf.filter((it) => it.t === 'station' && !MOSEL_STOPS_TRIER.includes(it.name)).map((it) => it.name),
    },
    moselSlice('Koblenz Hbf')
  );

  /* ---------------------------------------------------------------- 7 metz (TER C40+ Luxembourg - Metz - Nancy: Howald, Bettembourg, Hettange-Grande, Thionville, Uckange, Hagondange, Walygator Parc, Metz, Pagny-sur-Moselle, Pont-à-Mousson, Nancy)
   * Real OSM geometry like the Luxembourg routes (real-metz.js, scripts/zuch/build_real_route.py with the two-stage corridor fetch; REAL-LINES.md "W3: abroad routes"). */
  const metz = makeRoute(
    {
      id: 'metz', kind: 'rail', region: 'Frankräich', cruise: 140, biomes: ['city', 'suburb', 'farmland', 'industrial', 'forest'],
      name: { lb: 'Lëtzebuerg – Metz – Nancy', de: 'Luxemburg – Metz – Nancy', en: 'Luxembourg – Metz – Nancy' },
    },
    lastAsTerminus(realLineBody('metz'))
  );

  /* ------------------------------------------------------------ 8 brussels (IC 16: Arlon, Marbehan, Libramont, Jemelle, Marloie, Ciney, Namur, Gembloux, Ottignies, Bruxelles-Luxembourg, Bruxelles-Midi)
   * Real OSM geometry (real-brussels.js), the Brussels north-south tunnel included; Schuman / Nord / Central are passed underground. */
  const brussels = makeRoute(
    {
      id: 'brussels', kind: 'rail', region: 'Belsch', cruise: 140, biomes: ['city', 'suburb', 'farmland', 'forest', 'ardennes', 'industrial'],
      name: { lb: 'Lëtzebuerg – Arlon – Namur – Bréissel', de: 'Luxemburg – Arlon – Namur – Brüssel', en: 'Luxembourg – Arlon – Namur – Brussels' },
    },
    lastAsTerminus(realLineBody('brussels'))
  );

  /* --------------------------------------------------------------- 9 paris (TGV 803B: Thionville, Metz, Champagne-Ardenne TGV, LGV Est) */
  const paris = makeRoute(
    {
      id: 'paris', kind: 'hst', region: 'Frankräich', cruise: 320, biomes: ['city', 'suburb', 'highspeed', 'farmland', 'forest', 'industrial', 'vineyard'],
      name: { lb: 'TGV Lëtzebuerg – Paräis-Est', de: 'TGV Luxemburg – Paris-Est', en: 'TGV Luxembourg – Paris-Est' },
    },
    lastAsTerminus(realLineBody('paris'))
  );

  const list = [west, south, east, wittlich, north, trier, metz, brussels, paris];

  /* Return direction: every route can also be driven the other way. The id of that direction is `<routeId>~r`; it is derived here (same
     ownership / price / career as the forward route, see TS.routeDir). TS.track.build(def) understands def.reverse + def.base. */
  const REV = '~r';
  const baseId = (id) => (typeof id === 'string' && id.endsWith(REV) ? id.slice(0, -REV.length) : id);
  const isReverse = (id) => typeof id === 'string' && id.endsWith(REV);
  function reverseName(def) {
    const names = def.stations || [];
    const first = names[0];
    const last = names[names.length - 1];
    const out = {};
    ['lb', 'de', 'en'].forEach((lang) => {
      const src = (def.name && def.name[lang]) || (def.name && def.name.en) || def.id;
      const prefix = (src.match(/^(.*?:\s*|TGV\s+)/) || ['', ''])[1];
      out[lang] = first && last ? prefix + last + ' → ' + first : src + ' ←';
    });
    return Object.freeze(out);
  }
  const reversed = new Map();
  function reverseDef(def) {
    if (!reversed.has(def.id)) {
      const r = Object.create(def);   // everything else (layout, length getter, luxtram spec, defaults) is inherited from the forward route
      Object.defineProperties(r, {
        id: { value: def.id + REV, enumerable: true }, name: { value: reverseName(def), enumerable: true },
        stations: { value: Object.freeze((def.stations || []).slice().reverse()), enumerable: true },
        reverse: { value: true, enumerable: true }, base: { value: def, enumerable: true },
      });
      reversed.set(def.id, Object.freeze(r));
    }
    return reversed.get(def.id);
  }
  function makeRoutes(routeList) {
    const byId = routeList.reduce((acc, r) => Object.assign(acc, { [r.id]: r }), {});
    return Object.freeze({
      list: routeList,
      get: (id) => byId[id] || (isReverse(id) && byId[baseId(id)] ? reverseDef(byId[baseId(id)]) : null),
    });
  }

  window.TS.routeDir = Object.freeze({ REV, baseId, isReverse, makeRoutes, reverseDef });
  window.TS.routes = makeRoutes(list);
})();
